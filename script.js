  const translateStatic = (lang) => {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const parent = node.parentElement;
      if (!parent || ['SCRIPT','STYLE','NOSCRIPT'].includes(parent.tagName)) return;
      const value = node.nodeValue;
      const trimmed = value.trim();
      if (!trimmed) return;
      if (!node.__haqiqEn && staticAr[trimmed]) node.__haqiqEn = trimmed;
      if (!node.__haqiqEn) return;
      const translated = lang === 'ar' ? staticAr[node.__haqiqEn] : node.__haqiqEn;
      node.nodeValue = value.replace(trimmed, translated);
    });
    document.querySelectorAll('input[placeholder]').forEach((input) => {
      if (!input.dataset.placeholderEn) input.dataset.placeholderEn = input.placeholder;
      input.placeholder = lang === 'ar' ? ({
        'Acme Trading':'شركة أكمي',
        'Ahmed Mansoor':'أحمد منصور',
        'ahmed@company.com':'ahmed@company.com',
        'United Arab Emirates':'المملكة العربية السعودية'
      }[input.dataset.placeholderEn] || input.dataset.placeholderEn) : input.dataset.placeholderEn;
    });
  };

  function initThemeToggle() {
    const buttons = [...document.querySelectorAll('.theme-toggle')];
    const applyTheme = (theme, persist = true) => {
      document.documentElement.dataset.theme = theme;
      if (persist) localStorage.setItem('haqiq-theme', theme);
      const isDark = theme === 'dark';
      buttons.forEach((button) => {
        const icon = button.querySelector('.theme-icon');
        if (icon) icon.textContent = isDark ? '☀' : '☾';
        button.setAttribute('aria-label', isDark ? (currentLang === 'ar' ? 'التبديل إلى الوضع الفاتح' : 'Switch to light mode') : (currentLang === 'ar' ? 'التبديل إلى الوضع الداكن' : 'Switch to dark mode'));
        button.setAttribute('title', button.getAttribute('aria-label'));
        button.setAttribute('aria-pressed', String(isDark));
      });
    };
    applyTheme(document.documentElement.dataset.theme || 'light', false);
    buttons.forEach((button) => button.addEventListener('click', () => applyTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark')));
    return () => applyTheme(document.documentElement.dataset.theme || 'light', false);
  }

